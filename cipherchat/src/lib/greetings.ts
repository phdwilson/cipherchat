// 随机取一条（避免与上次重复，增加新鲜感）
const LAST_KEY = 'cipherchat_last_greeting'
export function randomGreeting(): string {
  if (CHANNEL_GREETINGS.length === 0) return '👋 欢迎回来'
  let pick = CHANNEL_GREETINGS[Math.floor(Math.random() * CHANNEL_GREETINGS.length)]
  try {
    const last = localStorage.getItem(LAST_KEY)
    if (last && CHANNEL_GREETINGS.length > 1) {
      let guard = 0
      while (pick === last && guard < 8) {
        pick = CHANNEL_GREETINGS[Math.floor(Math.random() * CHANNEL_GREETINGS.length)]
        guard++
      }
    }
    localStorage.setItem(LAST_KEY, pick)
  } catch { /* ignore */ }
  return pick
}

// timeAgo 相对时间
export function timeAgo(iso: string | number): string {
  const t = new Date(iso).getTime()
  if (!Number.isFinite(t)) return '未知'
  const diff = Date.now() - t
  if (diff < 0) return '刚刚' // v1.7.0：未来时间（客户端时钟偏差）不再显示负数
  if (diff < 60_000) return '刚刚'
  if (diff < 3600_000) return `${Math.floor(diff / 60_000)} 分钟前`
  if (diff < 86400_000) return `${Math.floor(diff / 3600_000)} 小时前`
  return `${Math.floor(diff / 86400_000)} 天前`
}
